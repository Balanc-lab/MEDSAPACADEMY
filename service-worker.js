self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(CORE);
    // Discover every data file, simulated screen and admin screenshot from the catalog.
    try {
      const cat = await (await fetch('data/catalog.json', { cache: 'no-cache' })).json();
      const urls = new Set(['data/catalog.json']);
      Object.values(cat).forEach((v) => { if (typeof v === 'string' && v.endsWith('.json')) urls.add(v); else if (Array.isArray(v)) v.forEach((u) => urls.add(u)); });
      const screens = await (await fetch(cat.screens, { cache: 'no-cache' })).json();
      Object.values(screens).forEach((s) => s.screens.forEach((x) => urls.add(x.src)));
      const reg = await (await fetch(cat.annotations, { cache: 'no-cache' })).json();
      (reg.annotations || []).forEach((a) => { if (a.file) urls.add(a.file); if (a.screenshot) urls.add(a.screenshot); });
      await Promise.all([...urls].map((u) => cache.add(new Request(u, { cache: 'no-cache' })).catch(() => null)));
    } catch (e) { /* partial precache: the rest is cached on first use */ }
    if (!self.registration.active) self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith('logiacademy-') && k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
    const clients = await self.clients.matchAll({ includeUncontrolled: true });
    clients.forEach((c) => c.postMessage({ type: 'precached', version: VERSION }));
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'skipWaiting') self.skipWaiting();
});

function timeout(ms) { return new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms)); }

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const res = await Promise.race([fetch(req), timeout(4000)]);
        if (res && res.ok) { const c = await caches.open(CACHE); c.put(req, res.clone()); }
        return res;
      } catch (e) {
        const cache = await caches.open(CACHE);
        const path = url.pathname.endsWith('studio.html') ? 'studio.html' : 'index.html';
        return (await cache.match(req, { ignoreSearch: true })) || (await cache.match(path)) || (await cache.match('offline.html'));
      }
    })());
    return;
  }

  if (url.pathname.includes('/data/')) {
    // stale-while-revalidate: instant answer from cache, refreshed in the background
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(req, { ignoreSearch: true });
      const network = fetch(req).then((res) => { if (res && res.ok) cache.put(req, res.clone()); return res; }).catch(() => null);
      if (cached) { event.waitUntil(network); return cached; }
      const res = await network;
      return res || new Response('{}', { status: 503, headers: { 'Content-Type': 'application/json' } });
    })());
    return;
  }

  // cache-first for the app shell, fonts, icons and screen images
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      const res = await fetch(req);
      if (res && res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    } catch (e) {
      return new Response('', { status: 504, statusText: 'Offline' });
    }
  })());
});
